#!/usr/bin/env node
/**
 * Optional white-label build step for the Open WebUI KB overlay.
 *
 * Rules:
 *   - Requires WHITE_LABEL_LEGAL_CLEARANCE=1. The script refuses to run without it.
 *   - Asset paths are read from environment variables; no brand assets are committed.
 *   - Custom assets are copied to upstream/static/kb-brand/ and referenced by a
 *     generated CSS override.
 *   - A CSS link is injected into upstream/src/app.html at build time only.
 *   - The original app.html is restored after the build so the default build
 *     remains unchanged.
 *   - Open WebUI copyright / attribution / LICENSE comments are left intact.
 */

import { execSync } from 'node:child_process';
import { cp, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const upstream = join(root, 'upstream');
const brandDir = join(upstream, 'static', 'kb-brand');
const appHtmlPath = join(upstream, 'src', 'app.html');
const appHtmlBackupPath = `${appHtmlPath}.white-label-backup`;
const cssPath = join(brandDir, 'white-label.css');

const ASSET_VARS = [
	{ env: 'WEBUI_LOGO_PATH', key: 'logo' },
	{ env: 'WEBUI_FAVICON_PATH', key: 'favicon' },
	{ env: 'WEBUI_SPLASH_LIGHT_PATH', key: 'splashLight' },
	{ env: 'WEBUI_SPLASH_DARK_PATH', key: 'splashDark' },
];

async function exists(p) {
	try {
		await stat(p);
		return true;
	} catch {
		return false;
	}
}

function mimeTypeForFavicon(fileName) {
	const ext = fileName.split('.').pop()?.toLowerCase();
	switch (ext) {
		case 'svg':
			return 'image/svg+xml';
		case 'ico':
			return 'image/x-icon';
		case 'png':
			return 'image/png';
		case 'jpg':
		case 'jpeg':
			return 'image/jpeg';
		default:
			return 'image/png';
	}
}

async function restoreAppHtml() {
	if (await exists(appHtmlBackupPath)) {
		const original = await readFile(appHtmlBackupPath, 'utf-8');
		await writeFile(appHtmlPath, original);
		await rm(appHtmlBackupPath, { force: true });
	}
}

async function cleanBrandSource() {
	try {
		await rm(brandDir, { recursive: true, force: true });
	} catch {
		// ignore
	}
}

async function copyAsset(filePath, targetName) {
	if (!(await exists(filePath))) {
		throw new Error(`White-label asset not found: ${filePath}`);
	}
	const target = join(brandDir, targetName);
	await mkdir(dirname(target), { recursive: true });
	await cp(filePath, target, { force: true, preserveTimestamps: true });
	return targetName;
}

function generateCss(assets) {
	const lines = [
		'/* White-label brand override for the Open WebUI splash screen. */',
		'/* Open WebUI copyright, attribution, and LICENSE notices remain intact. */',
		'/* Generated by scripts/white-label-build.js — do not edit manually. */',
		'',
	];

	const overrides = [];
	const hasReplacement = assets.logo || assets.splashLight || assets.splashDark;

	if (hasReplacement) {
		overrides.push('#logo, #logo-her { display: none !important; }');
	}

	if (assets.splashLight || assets.splashDark) {
		overrides.push(
			'#splash-screen { background-position: center !important; background-repeat: no-repeat !important; background-size: contain !important; }',
		);
		if (assets.splashLight) {
			overrides.push(
				`#splash-screen { background-image: url('/static/kb-brand/${basename(assets.splashLight)}') !important; }`,
			);
		}
		if (assets.splashDark) {
			overrides.push(
				`html.dark #splash-screen { background-image: url('/static/kb-brand/${basename(assets.splashDark)}') !important; }`,
			);
		}
		// Mirror a single provided splash asset across both themes.
		if (assets.splashLight && !assets.splashDark) {
			overrides.push(
				`html.dark #splash-screen { background-image: url('/static/kb-brand/${basename(assets.splashLight)}') !important; }`,
			);
		}
		if (assets.splashDark && !assets.splashLight) {
			overrides.push(
				`#splash-screen { background-image: url('/static/kb-brand/${basename(assets.splashDark)}') !important; }`,
			);
		}
	}

	if (assets.logo) {
		overrides.push(
			`#splash-screen::before { content: ''; position: absolute; top: 44%; left: 50%; transform: translate(-50%, -50%); width: auto; height: 6rem; background-image: url('/static/kb-brand/${basename(assets.logo)}'); background-size: contain; background-repeat: no-repeat; background-position: center; }`,
		);
	}

	lines.push(...overrides);
	return lines.join('\n') + '\n';
}

async function injectAppHtml(assets) {
	const original = await readFile(appHtmlPath, 'utf-8');
	await writeFile(appHtmlBackupPath, original);

	let injection = '';
	injection += '\t\t<!-- WHITE-LABEL-INJECTION-START -->\n';
	injection +=
		'\t\t<!-- Custom brand assets injected by scripts/white-label-build.js. Open WebUI LICENSE and attribution remain intact. -->\n';

	if (assets.favicon) {
		const faviconFile = basename(assets.favicon);
		const faviconMime = mimeTypeForFavicon(faviconFile);
		injection += `\t\t<link rel="icon" type="${faviconMime}" href="/static/kb-brand/${faviconFile}" crossorigin="use-credentials" />\n`;
	}

	injection +=
		'\t\t<link rel="stylesheet" href="/static/kb-brand/white-label.css" crossorigin="use-credentials" />\n';
	injection += '\t\t<!-- WHITE-LABEL-INJECTION-END -->\n';

	const modified = original.replace('%sveltekit.head%', `${injection}\t\t%sveltekit.head%`);
	await writeFile(appHtmlPath, modified);
}

async function main() {
	if (process.env.WHITE_LABEL_LEGAL_CLEARANCE !== '1') {
		console.error(
			'[white-label-build] Refusing to run: WHITE_LABEL_LEGAL_CLEARANCE=1 is required.',
		);
		console.error(
			'[white-label-build] Final asset ownership and legal clearance are the owner\'s responsibility.',
		);
		process.exit(1);
	}

	if (!(await exists(upstream))) {
		console.error(
			'[white-label-build] upstream/ directory not found. Run ./setup-openwebui.sh first.',
		);
		process.exit(1);
	}

	// Ensure a clean starting point if a previous run was interrupted.
	await restoreAppHtml();
	await cleanBrandSource();

	console.log('[white-label-build] Merging KB overlay into upstream...');
	execSync('npm run kb:merge', { cwd: root, stdio: 'inherit' });

	const assets = {};
	for (const { env, key } of ASSET_VARS) {
		const value = process.env[env];
		if (value) {
			console.log(`[white-label-build] Copying ${env} -> ${value}`);
			assets[key] = await copyAsset(value, basename(value));
		} else {
			console.warn(`[white-label-build] ${env} not set; using default Open WebUI asset.`);
		}
	}

	await mkdir(brandDir, { recursive: true });

	const css = generateCss(assets);
	await writeFile(cssPath, css);
	console.log(`[white-label-build] Generated ${cssPath}`);

	console.log('[white-label-build] Injecting white-label CSS link into app.html...');
	await injectAppHtml(assets);

	console.log('[white-label-build] Running upstream Vite build...');
	execSync('node --max-old-space-size=6144 node_modules/vite/bin/vite.js build', {
		cwd: upstream,
		stdio: 'inherit',
	});

	console.log('[white-label-build] Build complete.');
}

main()
	.catch(async (err) => {
		console.error('[white-label-build] Failed:', err.message);
		process.exitCode = 1;
	})
	.finally(async () => {
		// Always restore the source tree so the default build is unaffected.
		await restoreAppHtml();
		await cleanBrandSource();
	});
